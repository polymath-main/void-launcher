#!/usr/bin/env python3
"""Area 07 step 8 — generate docs/SCHEMA.md from LauncherConfig.kt.

Parses the data-class fields (name, type, default, trailing comment),
the serializer's JSON keys from ConfigManager.kt, and a Settings-exposure
heuristic (field referenced as cfg.<field> in VoidSettingsActivity.kt).
Re-run after changing LauncherConfig: python3 scripts/generate-schema-doc.py
SchemaDocTest fails if a field is added without regenerating this doc.
"""
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "app/src/main/java/com/polymath/voidlauncher/model/LauncherConfig.kt"
MGR = REPO / "app/src/main/java/com/polymath/voidlauncher/core/ConfigManager.kt"
ACT = REPO / "app/src/main/java/com/polymath/voidlauncher/VoidSettingsActivity.kt"
OUT = REPO / "docs/SCHEMA.md"

def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()

def parse_class(src, start_marker):
    i = src.index(start_marker)
    depth = 0
    fields = []
    pending_deprecated = False
    for line in src[i:].splitlines():
        if "DEPRECATED" in line:
            pending_deprecated = True
        depth += line.count("(") - line.count(")")
        m = re.match(r'\s*val\s+(\w+)\s*:\s*([\w<>,\s?]+?)\s*=\s*(.+?)\s*(?://\s*(.*))?$', line)
        if m and depth >= 1:
            name, typ, default, comment = m.groups()
            fields.append({
                "name": name, "type": typ.strip(), "default": default.strip(),
                "comment": (comment or "").strip(), "deprecated": pending_deprecated,
            })
            pending_deprecated = False
        if depth <= 0 and fields:
            break
    return fields

src = SRC.read_text()
mgr = MGR.read_text()
act = ACT.read_text()

# Serializer JSON keys: put("key", config.<field> ...)
ser_keys = dict(re.findall(r'put\("([^"]+)",\s*config\.(\w+)', mgr))
color_keys = dict(re.findall(r'put\("([^"]+)",\s*config\.colors\.(\w+)', mgr))

config_fields = parse_class(src, "data class LauncherConfig(")
color_fields = parse_class(src, "data class ColorPalette(")

def settings_exposed(name):
    return f"cfg.{name}" in act or f"{name} =" in act

lines = []
lines.append("# VoidLauncher config schema (generated)")
lines.append("")
lines.append("> Generated by `scripts/generate-schema-doc.py` from")
lines.append("> `model/LauncherConfig.kt` + the serializer in `core/ConfigManager.kt`.")
lines.append("> Do not hand-edit the tables — regenerate after changing a field;")
lines.append("> `SchemaDocTest` fails if a field is added without a doc row.")
lines.append("")
lines.append("Store file: `<external-files>/config/config.json` (`VoidPaths.CONFIG`).")
lines.append("Load: 4-tier (store → internal → bundled asset → Kotlin defaults),")
lines.append("lenient per-field fallback; unknown keys are warned about, never a")
lines.append("whole-file rejection. `schema_version` is advisory (current 1).")
lines.append("Export writes the CURRENT config, never defaults (1.1.0 fix).")
lines.append("Settings SAVE TO STORE saves to the store; EXPORT FILE… is the SAF")
lines.append("picker export. A config file can reveal directory paths and package")
lines.append("names — share carefully (the export toast says so too).")
lines.append("")
lines.append("## LauncherConfig fields")
lines.append("")
lines.append("| Field | JSON key | Type | Default | Settings-exposed | Notes |")
lines.append("|---|---|---|---|---|---|")
for f in config_fields:
    key = ser_keys.get(f["name"], snake(f["name"]))
    exposed = "yes" if settings_exposed(f["name"]) else "JSON-only"
    note = f["comment"]
    if f["deprecated"]:
        note = "DEPRECATED. " + note
    lines.append(f"| `{f['name']}` | `{key}` | `{f['type']}` | `{f['default']}` | {exposed} | {note} |")
lines.append("")
lines.append("## colors.* (nested object `colors`)")
lines.append("")
lines.append("| Field | JSON key | Type | Default | Settings-exposed | Notes |")
lines.append("|---|---|---|---|---|---|")
for f in color_fields:
    key = color_keys.get(f["name"], snake(f["name"]))
    exposed = "partial (customizer)" if f["name"] in ("accent", "secondary", "surface") else "JSON-only"
    lines.append(f"| `{f['name']}` | `colors.{key}` | `{f['type']}` | `{f['default']}` | {exposed} | {f['comment']} |")
lines.append("")
lines.append("## Deprecated fields (kept so old configs still parse)")
lines.append("")
lines.append("- `thermalKillCommands` — never executed as shell (area 01 step 8);")
lines.append("  removal is a major-version decision, not a silent field drop.")
lines.append("- `defaultIdentity` — migration-only fallback; `activePersona` is the")
lines.append("  single source of truth since area 06 step 3.")
lines.append("")
OUT.write_text("\n".join(lines))
print(f"wrote {OUT}: {len(config_fields)} config fields, {len(color_fields)} color fields")
